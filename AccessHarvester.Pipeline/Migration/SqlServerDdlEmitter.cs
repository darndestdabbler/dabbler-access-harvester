using System.Collections.Generic;
using System.Text;

namespace AccessHarvester.Pipeline.Migration;

/// <summary>
/// Emits deterministic SQL Server schema DDL text from a resolved
/// <see cref="MigrationSchema"/> (<c>CREATE TABLE</c> + primary keys, then
/// post-create <c>ALTER TABLE ... ADD FOREIGN KEY</c>). Pure text assembly — all
/// "what survives" decisions are already made by <see cref="MigrationSchemaResolver"/>.
/// Output uses fixed LF newlines and carries no timestamps, so it is byte-stable
/// for golden comparison regardless of host OS.
/// </summary>
public static class SqlServerDdlEmitter
{
    /// <summary>
    /// Fixed line terminator. Emitted as explicit <c>\n</c> (never
    /// <c>Environment.NewLine</c>) so the artifact is byte-identical across OSes.
    /// </summary>
    internal const string NL = "\n";

    public static string Emit(MigrationSchema schema)
    {
        var tableSql = new List<string>();
        foreach (var t in schema.Tables)
            tableSql.Add(BuildCreateTable(t));

        var fkSql = new List<string>();
        foreach (var fk in schema.ForeignKeys)
            fkSql.Add(BuildForeignKey(fk));

        return Assemble(schema.Database, tableSql, fkSql);
    }

    private static string BuildCreateTable(MigrationResolvedTable table)
    {
        var body = new List<string>();
        foreach (var c in table.Columns)
            body.Add(BuildColumnLine(c));

        if (table.PrimaryKeyColumns is { Count: > 0 } pk)
        {
            string cols = string.Join(", ", System.Linq.Enumerable.Select(pk, Quote));
            body.Add($"CONSTRAINT {Quote("PK_" + table.Name)} PRIMARY KEY ({cols})");
        }

        var sb = new StringBuilder();
        sb.Append("CREATE TABLE ").Append(Quote(table.Name)).Append(" (").Append(NL);
        for (int i = 0; i < body.Count; i++)
        {
            sb.Append("    ").Append(body[i]);
            if (i < body.Count - 1) sb.Append(',');
            sb.Append(NL);
        }
        sb.Append(");");
        return sb.ToString();
    }

    private static string BuildColumnLine(MigrationResolvedColumn c)
    {
        var sb = new StringBuilder();
        sb.Append(Quote(c.Name)).Append(' ').Append(c.SqlType);
        if (c.IsIdentity) sb.Append(" IDENTITY(1,1)");
        sb.Append(c.NotNull ? " NOT NULL" : " NULL");
        if (c.SqlDefault is not null) sb.Append(" DEFAULT (").Append(c.SqlDefault).Append(')');
        return sb.ToString();
    }

    private static string BuildForeignKey(MigrationResolvedForeignKey fk)
    {
        string childList = string.Join(", ", System.Linq.Enumerable.Select(fk.FieldPairs, p => Quote(p.ChildField)));
        string parentList = string.Join(", ", System.Linq.Enumerable.Select(fk.FieldPairs, p => Quote(p.ParentField)));

        var sb = new StringBuilder();
        sb.Append("ALTER TABLE ").Append(Quote(fk.ChildTable))
          .Append(" ADD CONSTRAINT ").Append(Quote(fk.ConstraintName))
          .Append(" FOREIGN KEY (").Append(childList).Append(')')
          .Append(" REFERENCES ").Append(Quote(fk.ParentTable))
          .Append(" (").Append(parentList).Append(')');
        if (fk.CascadeUpdate) sb.Append(" ON UPDATE CASCADE");
        if (fk.CascadeDelete) sb.Append(" ON DELETE CASCADE");
        sb.Append(';');
        return sb.ToString();
    }

    private static string Assemble(string database, List<string> tableSql, List<string> fkSql)
    {
        var sb = new StringBuilder();
        Line(sb, "-- =====================================================================");
        Line(sb, "-- SQL Server migration script (schema) for database: " + database);
        Line(sb, "-- Generated by AccessHarvester generate-migration.");
        Line(sb, "-- Deterministic: fixed LF newlines, no timestamps. Review flagged degradations in the manifest.");
        Line(sb, "-- =====================================================================");
        Line(sb, "");
        Line(sb, "-- ---------------------------------------------------------------------");
        Line(sb, "-- Tables");
        Line(sb, "-- ---------------------------------------------------------------------");
        foreach (var t in tableSql)
        {
            Line(sb, "");
            Line(sb, t);
            Line(sb, "GO");
        }

        if (fkSql.Count > 0)
        {
            Line(sb, "");
            Line(sb, "-- ---------------------------------------------------------------------");
            Line(sb, "-- Foreign keys");
            Line(sb, "-- ---------------------------------------------------------------------");
            foreach (var fk in fkSql)
            {
                Line(sb, "");
                Line(sb, fk);
                Line(sb, "GO");
            }
        }

        return sb.ToString();
    }

    /// <summary>Appends <paramref name="text"/> followed by the fixed LF terminator.</summary>
    private static void Line(StringBuilder sb, string text) => sb.Append(text).Append(NL);

    /// <summary>Bracket-quotes a SQL Server identifier, doubling any embedded <c>]</c>.</summary>
    internal static string Quote(string identifier) => "[" + identifier.Replace("]", "]]") + "]";
}
