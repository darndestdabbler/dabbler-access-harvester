"""Route the next-orchestrator recommendation for Session 3.

Per the workflow doc, the orchestrator never self-opines; the
recommendation is generated by routed analysis (gemini-pro at
task_type='analysis', per the established pattern).
"""

import pathlib

from ai_router import route
from ai_router.session_log import SessionLog

SESSION_SET = pathlib.Path("docs/session-sets/harvester-finish-operations-and-interpretation-docs")
SESSION_NUMBER = 2  # the session that is closing; routing for N+1=3


def _read(path: pathlib.Path) -> str:
    return path.read_text(encoding="utf-8")


def main() -> int:
    log = SessionLog(str(SESSION_SET))
    spec = _read(SESSION_SET / "spec.md")

    actuals_summary = """
Session 2 actuals (just completed):
- Orchestrator: Claude Opus 4.7 @ effort=high (matched recommendation).
- Body authored in-conversation per the "Use Opus as the orchestrator for synthesis-document work above ~3K input tokens" Convention.
- Routed cost: ~$0.028 (one gemini-pro session-verification call after an OpenAI 429 forced rung-2 of the verifier-failure escalation ladder). OpenAI 429 condition persists from Session 1; expect the same for Session 3.
- Verdict: VERIFIED (terse but JSON-block-compliant; the required-JSON-block convention saved a re-prompt).
- Deliverables: docs/harvester/interpretation-guide.md (4,711 words; within outline budget).
"""

    prompt = f"""You are advising on which orchestrator should run Session 3 of this set.

Spec (for the Session 3 step list):

```markdown
{spec}
```

{actuals_summary}

Session 3 is the closeout session. Its steps are:
1. Author docs/README.md (the pointer page listing every doc in
   docs/ and its subdirectories).
2. Add a link from the top-level README.md to the new
   interpretation guide.
3. Downstream-AI probe: hand the full guide to a fresh
   cross-provider model and ask whether it can interpret a sample
   harvester output based only on the guide.
4. End-of-session verification.
5. Closeout artefacts: disposition.json, change-log.md,
   next-session-set-recommendation.md, commit + push +
   mark_session_complete() + notify.
6. Step 9 reorganization review (AFTER notify).

Recommend:
- Which orchestrator engine (Claude Code / Codex / Gemini CLI),
  which model, and which effort level.
- One short rationale (~2 sentences) tying the choice to the work mix.
- One sentence on routed-cost expectation.

Keep the response under 200 words; this feeds directly into the
ai-assignment.md next-session recommendation slot.
"""

    result = route(
        content=prompt,
        task_type="analysis",
        context="Recommend orchestrator/effort for Session 3.",
        session_set=str(SESSION_SET),
        session_number=SESSION_NUMBER,
    )

    # Persist to disk BEFORE any side effects per project-guidance.
    out_path = SESSION_SET / "next-orchestrator-recommendation-session-3.md"
    out_path.write_text(
        "# Next-Orchestrator Recommendation — Session 3\n\n"
        f"> **Routed via** `route(task_type=\"analysis\")` to "
        f"`{result.model_name}` "
        f"(${result.cost_usd:.4f}, "
        f"in={result.input_tokens}, out={result.output_tokens}).\n\n"
        f"{result.content}\n",
        encoding="utf-8",
    )

    print(f"Saved recommendation to: {out_path}")
    print(f"Model: {result.model_name}")
    print(f"Cost:  ${result.cost_usd:.4f}")

    log.log_step(
        session_number=SESSION_NUMBER,
        step_number=4,
        step_key="session-2/next-orc-rec",
        description=f"Routed analysis: next-orchestrator recommendation for Session 3 (model={result.model_name}).",
        status="complete",
        api_calls=[{
            "model": result.model_name,
            "taskType": "analysis",
            "inputTokens": result.input_tokens,
            "outputTokens": result.output_tokens,
            "costUsd": result.cost_usd,
        }],
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
